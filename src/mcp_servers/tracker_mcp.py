"""tracker_mcp — Standalone MCP server for issue tracking via Postgres.

Receives only DATABASE_URL. Run over stdio with `python -m src.mcp_servers.tracker_mcp`.

Exposes:
    search_existing_issues(exception_type, file_name) -> list[IssueRecord]
    create_issue(title, root_cause, commit_sha, severity) -> IssueRecord
    draft_hotfix_pr(commit_sha, file_path, patch_summary) -> PRPreview
"""


from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from functools import cache

from mcp.server.mcpserver import MCPServer
from pydantic import SecretStr
from pydantic_settings import BaseSettings, SettingsConfigDict
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from src.db.engine import create_engine_for, make_session_factory
from src.repositories import issues as repo
from src.schemas.mcp.tracker import IssueRecord, PRPreview


class TrackerServerSettings(BaseSettings):
    """The only configuration this server can see (least privilege)."""

    database_url: SecretStr = SecretStr("")

    model_config = SettingsConfigDict(env_file=".env", extra="ignore")


settings = TrackerServerSettings()


@cache
def session_factory() -> async_sessionmaker[AsyncSession]:
    """Created on first use so the server still starts when the database is down."""
    return make_session_factory(create_engine_for(settings.database_url.get_secret_value()))


@asynccontextmanager
async def session_scope() -> AsyncIterator[AsyncSession]:
    """One transaction: commit if the block succeeds, roll back if it raises."""
    async with session_factory().begin() as session:
        yield session


# ── Public API ────────────────────────────────────────────────────


async def search_existing_issues(
    exception_type: str,
    file_name: str,
    limit: int = 5,
) -> list[IssueRecord]:
    """Return open issues sharing the exception type OR the file — dedup *candidates*.

    Deliberately broad: whether a candidate is truly the same bug is decided by the
    triage model in the dedup node, not by string equality.
    """
    async with session_scope() as session:
        rows = await repo.find_dedup_candidates(session, exception_type, file_name, limit)
    return [IssueRecord.model_validate(row, from_attributes=True) for row in rows]


async def create_issue(
    title: str,
    root_cause: str,
    commit_sha: str,
    severity: str,
    exception_type: str = "",
    file_name: str = "",
) -> IssueRecord:
    """Insert a new issue and return the created record."""
    if severity not in ("low", "medium", "high", "critical"):
        raise ValueError(f"severity must be one of low/medium/high/critical, got {severity!r}")

    async with session_scope() as session:
        row = await repo.add_issue(
            session,
            title=title,
            exception_type=exception_type,
            file_name=file_name,
            root_cause=root_cause,
            commit_sha=commit_sha,
            severity=severity,
        )
    return IssueRecord.model_validate(row, from_attributes=True)


async def draft_hotfix_pr(
    commit_sha: str,
    file_path: str,
    patch_summary: str,
) -> PRPreview:
    """Return a structured PR preview object (stubbed — no actual PR created).

    In a production deployment this would call GitHub/GitLab APIs after
    human-in-the-loop approval.
    """
    # Sanitise branch name from the commit SHA
    short_sha = commit_sha[:7] if len(commit_sha) >= 7 else commit_sha
    branch_name = f"hotfix/{short_sha}"

    # Derive a title from the file and summary
    file_base = file_path.rsplit("/", maxsplit=1)[-1] if "/" in file_path else file_path
    title = f"fix({file_base}): {patch_summary[:80]}"

    description = (
        f"## Hotfix PR (Draft)\n\n"
        f"**Root-cause commit:** `{commit_sha}`\n\n"
        f"**File:** `{file_path}`\n\n"
        f"### Summary\n{patch_summary}\n\n"
        f"---\n"
        f"_Auto-generated by Sentinel-RCA. Requires human approval before merge._"
    )

    return PRPreview(
        title=title,
        branch_name=branch_name,
        commit_sha=commit_sha,
        file_path=file_path,
        patch_summary=patch_summary,
        description=description,
        status="draft",
    )


server = MCPServer("tracker_mcp")
for _tool in (search_existing_issues, create_issue, draft_hotfix_pr):
    server.add_tool(_tool)


if __name__ == "__main__":
    server.run()
